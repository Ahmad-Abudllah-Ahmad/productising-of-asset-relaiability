export const translations: Record<Language, Record<string, string>> = { en, az };

export function translate(language: Language, key: TranslationKey): string {
  return translations[language]?.[key] ?? translations.en[key] ?? key;
}

const PROGRESS_LABEL_KEYS: Record<string, string> = {
  "Complete": "progressLabel.complete",
  "Queued": "progressLabel.queued",
  "Analyzing...": "progressLabel.analyzing",
  "Pending": "progressLabel.pending",
  "Uploading...": "progressLabel.uploading",
  "Cancelled": "progressLabel.cancelled",
};

/** Translates a raw English card progress label (e.g. "Uploading...") if recognized, else returns it unchanged. */
export function translateProgressLabel(language: Language, label: string): string {
  const key = PROGRESS_LABEL_KEYS[label];
  return key ? translate(language, key) : label;
}

/** Translates a key and substitutes `{param}` placeholders with the provided values. */
export function translateWithParams(
  language: Language,
  key: TranslationKey,
  params: Record<string, string | number>
): string {
  let result = translate(language, key);
  for (const [name, value] of Object.entries(params)) {
    result = result.replace(`{${name}}`, String(value));
  }
  return result;
}

const STATUS_TRANSLATION_KEYS: Record<string, string> = {
  completed: "common.completed",
  processing: "common.processing",
  failed: "common.failed",
  pending: "common.pending",
  approved: "common.approved",
  rejected: "common.rejected",
  canceled: "common.canceled",
  cancelled: "common.canceled",
};

/** Normalizes a raw detection class name to a lookup key. */
function normalizeDetectionClassKey(raw: string): string {
  return String(raw ?? "")
    .trim()
    .toLowerCase()
    .replace(/-/g, "_")
    .replace(/\s+/g, "_");
}

/** Translates a detection class key (e.g. "broken_disc", "insulator") for display. */
export function translateDetectionClassKey(language: Language, raw: string): string {
  const key = normalizeDetectionClassKey(raw);
  if (!key) return translate(language, "detectionClass.unknown");
  const translationKey = `detectionClass.${key}` as TranslationKey;
  const translated = translate(language, translationKey);
  if (translated !== translationKey) return translated;
  return key.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

/** Translates a run/batch status string (e.g. "completed", "processing"). */
export function translateStatus(
  status: string | undefined | null,
  t: (key: string) => string
): string {
  if (!status) return "—";
  const key = STATUS_TRANSLATION_KEYS[status.toLowerCase()];
  return key ? t(key) : status;
}
