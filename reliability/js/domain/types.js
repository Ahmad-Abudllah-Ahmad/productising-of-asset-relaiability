// Shared vocabulary and JSDoc typedefs for the Reliability module.
// Pure data definitions: no logic, no DOM, no I/O.

/** @typedef {'line_network'|'structure'|'line_component'|'right_of_way'|'substation'|'transformer'|'inspection_evidence'} AssetCategory */

/**
 * Categories from the plan's asset model. `inspection_evidence` is a category in the model,
 * but campaigns, captures and findings are stored in their own collections, never as assets.
 */
export const ASSET_CATEGORIES = Object.freeze([
  'line_network', 'structure', 'line_component', 'right_of_way',
  'substation', 'transformer', 'inspection_evidence',
]);

/** Asset classes per category (snake_case ids). Not every class is generated by the seed. */
export const ASSET_CLASSES = Object.freeze({
  line_network: ['corridor', 'line', 'section', 'span'],
  structure: ['tower', 'foundation'],
  line_component: [
    'conductor', 'earthwire', 'insulator_string', 'damper', 'spacer',
    'clamp', 'jumper', 'arrester', 'bird_diverter',
  ],
  right_of_way: ['span_corridor_segment'],
  substation: ['substation', 'bay'],
  transformer: ['power_transformer', 'bushing', 'tap_changer', 'cooling', 'tank_oil'],
  inspection_evidence: ['campaign', 'capture', 'finding'],
});

