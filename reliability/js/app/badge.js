// The Experimental badge and the Demo data banner. Both read the validation register (domain/validation.js) and the repository's
// data source, so nothing here decides on its own what is experimental or simulated.

import { h } from '../ui/dom.js';
import { explain, isExperimental, entryFor } from '../domain/validation.js';
import { syncedText } from './dataSource.js';

/** A small badge for a register entry, or null when the entry has been validated. Hover (or focus) says why. */
export function experimentalBadge(id, { small = true } = {}) {
  if (!isExperimental(id)) return null;
  return h('span', {
    class: `xp-badge${small ? '' : ' xp-badge-lg'}`, tabindex: '0', role: 'note', 'data-register': id, 'data-testid': `xp-${id}`,
    title: explain(id), 'aria-label': `Experimental: ${entryFor(id)?.name ?? id}. ${explain(id)}`,
  }, 'Experimental');
}

const escAttr = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
/** The same badge as markup, for tables built as HTML strings. */
export function experimentalBadgeHtml(id) {
  if (!isExperimental(id)) return '';
  return ` <span class="xp-badge" tabindex="0" role="note" data-register="${escAttr(id)}" data-testid="xp-${escAttr(id)}" title="${escAttr(explain(id))}" aria-label="${escAttr(`Experimental: ${entryFor(id)?.name ?? id}. ${explain(id)}`)}">Experimental</span>`;
}

/** The register entry a table column header belongs to ('Health index' or 'Risk'), or null. Badges go once per header, never per row. */
export const registerIdForColumn = (name) => (/^health index/i.test(name) ? 'health_index' : /^risk$/i.test(name) ? 'risk' : null);

/** Which register entry a KPI card label belongs to, or null. */
export function registerIdForLabel(text) {
  const t = String(text ?? '').toLowerCase();
  if (/health index/.test(t)) return 'health_index';
  if (/\brisk\b/.test(t)) return 'risk';
  return null;
}

/** Put the right badge on every KPI card in a strip (Health index, Risk). Safe to call twice. */
export function badgeKpis(root) {
  for (const k of root.querySelectorAll('.kpi .k')) {
    if (k.querySelector('.xp-badge')) continue;
    const id = registerIdForLabel(k.dataset.label ?? k.textContent);
    const b = id ? experimentalBadge(id) : null;
    if (b) { k.dataset.label = k.dataset.label ?? k.textContent.trim(); k.append(' ', b); }
  }
}

/** The label of a KPI card as the handlers know it, without any badge text. */
export const kpiLabel = (k) => (k.dataset.label ?? k.textContent ?? '').trim();

/** The banner under the top bar while the data source is the built-in seed (kept for callers that only know the source name). */
export function demoBanner(source) {
  if (source !== 'seed') return null;
  return h('div', { class: 'demo-banner', role: 'note', 'data-testid': 'demo-banner' },
    h('b', {}, 'Demo data'),
    h('span', {}, ' Everything on this page is generated by the built-in seed, not read from a company system. Experimental badges mark scores that have not been tested against real data.'));
}

/**
 * The banner under the top bar, with the data-source switch.
 *   seed   "Demo data": everything is generated (kept as it was in Phase A)
 *   erp    the ERP source is on: work orders, plans, stock and purchase orders come from the ERP; the Demo data banner is not shown
 *          (findings, images, LiDAR and scores are still the seed's and say so on screen)
 *   error  the ERP was chosen but could not be read: the demo data is shown, with the reason
 * @param {{source: string, label?: string, syncedAt?: string|null}} info  repository.sourceInfo()
 * @param {{error?: string|null, onSwitch: (value: 'seed'|'erp') => void}} o
 */
export function dataSourceBanner(info, { error = null, onSwitch }) {
  const select = h('select', { 'data-testid': 'source-switch', 'aria-label': 'Data source', onChange: (e) => onSwitch(e.target.value) },
    h('option', { value: 'seed', selected: info.source === 'seed' }, 'Demo data (built-in seed)'),
    h('option', { value: 'erp', selected: info.source === 'erp' }, 'ERP (mock SAP adapter)'));
  const switchEl = h('label', { class: 'src-switch' }, 'Data source ', select);
  if (info.source === 'erp') {
    return h('div', { class: 'demo-banner src-banner', role: 'note', 'data-testid': 'erp-banner' },
      h('b', {}, 'ERP data'),
      h('span', {}, ` Work orders, maintenance plans, stock, suppliers and purchase orders are read from ${info.label} (synced ${syncedText(info.syncedAt)}). Findings, images, the simulated LiDAR and every score are still generated by the built-in seed.`), switchEl);
  }
  const b = demoBanner('seed');
  b.classList.add('src-banner');
  if (error) b.append(h('span', { class: 'src-error', role: 'alert', 'data-testid': 'erp-error' }, ` The ERP source could not be used (${error}); showing the demo data instead.`));
  b.append(switchEl);
  return b;
}

/** "Source: demo data" or "Source: SAP (mock) · synced 16 Nov, 09:10", for any panel whose numbers come from the ERP source. */
export function sourceBadge(repo, { what = null, testid = 'source-badge' } = {}) {
  const info = repo?.sourceInfo?.() ?? { source: 'seed', label: 'demo data' };
  const text = info.source === 'erp' ? `Source: ${info.label} · synced ${syncedText(info.syncedAt)}` : 'Source: demo data';
  return h('span', { class: `src-badge${info.source === 'erp' ? ' is-erp' : ''}`, 'data-testid': testid, 'data-source': info.source, title: info.source === 'erp' ? 'Read from the ERP through the integration API (read-only).' : 'Generated by the built-in seed; no ERP is connected.' }, what ? `${what} · ` : '', text);
}
