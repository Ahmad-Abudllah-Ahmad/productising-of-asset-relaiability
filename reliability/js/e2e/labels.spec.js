// Phase A: the name "Asset Health", the Demo data banner on every screen, and the Experimental badges that read the validation
// register. Screenshots (both themes) go to docs/screens/phaseA/.
import { test, expect } from '@playwright/test';
import fs from 'node:fs';

const SHOTS = 'docs/screens/phaseA';
fs.mkdirSync(SHOTS, { recursive: true });
const t = (page, id) => page.getByTestId(id);
const theme = (page) => page.evaluate(() => document.documentElement.dataset.relTheme ?? 'light');
const rail = (page) => page.locator('[data-go]');

async function visit(page, url, th = 'light', size = { width: 1920, height: 1080 }) {
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.setViewportSize(size);
  await page.goto('/reliability');
  await page.evaluate((v) => localStorage.setItem('nexus.reliability.theme', v), th);
  await page.goto(url); await page.reload();
  await expect.poll(() => theme(page)).toBe(th);
  await expect(rail(page).first()).toBeVisible();
  return errors;
}
const openLinks = async (page) => { await rail(page).nth(2).click(); await page.locator('#tabs [data-tab]', { hasText: /^Links$/ }).click(); };
const shot = async (page, name, th) => { await page.waitForTimeout(700); await page.screenshot({ path: `${SHOTS}/${name}-${th}.png` }); };

test.describe('naming', () => {
  test('the page, the top bar, the rail and the dashboard say Asset Reliability (renamed back in Phase C), and the URL is unchanged', async ({ page }) => {
    await visit(page, '/reliability');
    await expect(page).toHaveTitle('Asset Reliability Intelligence');
    await expect(page.locator('#app-title')).toContainText('Asset Reliability Intelligence');
    await expect(page.locator('#app-title')).toContainText('Asset Reliability Dashboard');
    await expect(rail(page).first()).toHaveAttribute('aria-label', /Asset Reliability Dashboard/);
    await expect(page.getByRole('heading', { name: /Asset Reliability dashboard/ })).toBeVisible();
    expect(new URL(page.url()).pathname).toBe('/reliability');
    expect(await page.locator('body').innerText()).not.toMatch(/Asset Health dashboard|Asset Health Intelligence/i);
  });
});

test.describe('Demo data banner', () => {
  const SCREENS = [['dashboard', '/reliability'], ['lines', '/reliability#view=lines'], ['towers', '/reliability#view=towers'], ['history', '/reliability#view=history'], ['map', '/reliability#view=map&tiles=off']];
  for (const [name, url] of SCREENS) {
    test(`the ${name} screen shows the banner with its one-line explanation`, async ({ page }) => {
      await visit(page, url);
      await expect(t(page, 'demo-banner')).toBeVisible();
      await expect(t(page, 'demo-banner')).toContainText('Demo data');
      await expect(t(page, 'demo-banner')).toContainText('generated by the built-in seed');
      await expect(t(page, 'demo-banner')).toHaveCount(1);
    });
  }

  test('the banner is also on the Drawing screen and every registry tab, and there is exactly one', async ({ page }) => {
    await visit(page, '/reliability');
    for (let i = 1; i <= 6; i += 1) {
      await rail(page).nth(i).click();
      await expect(t(page, 'demo-banner')).toHaveCount(1);
      await expect(t(page, 'demo-banner')).toBeVisible();
    }
  });

  test('the banner does not cover the dashboard at 1920 x 1080 (nothing is pushed below the fold)', async ({ page }) => {
    await visit(page, '/reliability');
    await expect(t(page, 'trend-chart')).toHaveAttribute('data-ready', 'true');
    const over = await page.evaluate(() => { const m = document.querySelector('.hl-main-wrap') ?? document.scrollingElement; return m.scrollHeight - m.clientHeight; });
    expect(over).toBeLessThanOrEqual(40);
  });
});

test.describe('Experimental badges', () => {
  test('Asset 360: health index and risk carry the badge; hover text names the reason and the register entry', async ({ page }) => {
    await visit(page, '/reliability#asset=TWR-132-01-011');
    const panel = t(page, 'asset-panel');
    await expect(panel.locator('[data-register="health_index"]').first()).toBeVisible();
    await expect(panel.locator('[data-register="risk"]').first()).toBeVisible();
    const hi = panel.locator('[data-register="health_index"]').first();
    await expect(hi).toHaveText('Experimental');
    const title = await hi.getAttribute('title');
    expect(title).toMatch(/weights/);
    expect(title).toMatch(/Validation register entry: health_index \(reliability\/js\/domain\/validation\.js\)/);
    await hi.focus();
    await expect(hi).toBeFocused();
  });

  test('screens: dashboard, Line Health, Tower Health, Risk Map, Link Review and the finding viewer carry the right badges', async ({ page }) => {
    await visit(page, '/reliability');
    await expect(t(page, 'risks-card').locator('[data-register="risk"]')).toBeVisible();
    await expect(t(page, 'trend-card').locator('[data-register="health_index"]')).toBeVisible();
    await expect(t(page, 'lines-card').locator('[data-register="health_index"]')).toBeVisible();
    await visit(page, '/reliability#view=lines');
    await expect(t(page, 'line-score').locator('[data-register="health_index"]')).toBeVisible();
    await expect(t(page, 'hl-kpis').locator('[data-register="health_index"]').first()).toBeVisible();
    await visit(page, '/reliability#view=towers');
    await expect(t(page, 'hl-kpis').locator('[data-register="health_index"]').first()).toBeVisible();
    await expect(t(page, 'hl-kpis').locator('[data-register="risk"]').first()).toBeVisible();
    await visit(page, '/reliability#view=map&tiles=off');
    await expect(t(page, 'hl-head').locator('[data-register="risk_map"]')).toBeVisible();
    await visit(page, '/reliability#finding=F-0308');
    await expect(t(page, 'fact-confidence-row').locator('[data-register="finding_confidence"]')).toBeVisible();
    await expect(t(page, 'fact-confidence')).toHaveText('0.89');
  });

  test('Link Review: the match score carries the resemblance badge', async ({ page }) => {
    await visit(page, '/reliability');
    await openLinks(page);
    await t(page, 'queue-row').first().click();
    await expect(page.locator('.lr-detail [data-register="resemblance"]').first()).toBeVisible();
  });

  test('tables: one badge per column header (Health index, Risk), none per row — registry, Maintenance History, the Link Review queue', async ({ page }) => {
    await visit(page, '/reliability');
    for (const tabName of ['Lines', 'Towers', 'Spans', 'Transformers']) {
      await rail(page).nth(2).click();
      await page.locator('#tabs [data-tab]', { hasText: new RegExp(`^${tabName}$`) }).click();
      const table = page.locator('#stage table.reg-table');
      await expect(table).toBeVisible();
      const heads = await table.locator('thead th').allInnerTexts();
      const hi = heads.filter((x) => /^Health index/.test(x)).length; const risk = heads.filter((x) => /^Risk/.test(x)).length;
      await expect(table.locator('thead [data-register="health_index"]')).toHaveCount(hi);
      await expect(table.locator('thead [data-register="risk"]')).toHaveCount(risk);
      await expect(table.locator('tbody .xp-badge')).toHaveCount(0);
    }
    await rail(page).nth(2).click();
    await page.locator('#tabs [data-tab]', { hasText: /^Components$/ }).click();
    await expect(page.locator('#stage table.reg-table thead .xp-badge')).toHaveCount(0);
    await visit(page, '/reliability#view=history&unit=TWR-132-01-011');
    await expect(t(page, 'hl-head')).toBeVisible();
    await page.locator('#tabs [data-tab]', { hasText: /^Repairs$/ }).click();
    await expect(t(page, 'repairs')).toBeVisible();
    await expect(t(page, 'repairs').locator('thead [data-register="health_index"]')).toHaveCount(1);
    await expect(t(page, 'repairs').locator('tbody .xp-badge')).toHaveCount(0);
    await visit(page, '/reliability#view=history&unit=TWR-132-01-013');
    await expect(t(page, 'trend-card').locator('[data-register="health_index"]')).toBeVisible();
    await visit(page, '/reliability');
    await openLinks(page);
    await expect(page.locator('.lr-qhead [data-register="resemblance"]')).toHaveCount(1);
    await expect(page.locator('.lr-row .xp-badge')).toHaveCount(0);
  });

  test('KPI cards still open their drill-downs (the badge does not change the card label)', async ({ page }) => {
    await visit(page, '/reliability#view=lines');
    const card = t(page, 'hl-kpis').locator('.kpi', { hasText: 'Line health index' });
    await expect(card).toHaveClass(/is-drill/);
    await card.click();
    await expect(t(page, 'asset-panel')).toBeVisible();
  });

  test('screenshots: dashboard, Asset 360, Risk Map, Link Review, finding viewer; both themes', async ({ page }) => {
    for (const th of ['light', 'dark']) {
      await visit(page, '/reliability', th);
      await expect(t(page, 'trend-chart')).toHaveAttribute('data-ready', 'true');
      await shot(page, 'dashboard', th);
      await visit(page, '/reliability#view=lines', th); await shot(page, 'line-health', th);
      await visit(page, '/reliability#view=map&tiles=off', th); await shot(page, 'risk-map', th);
      await visit(page, '/reliability#asset=TWR-132-01-011', th); await shot(page, 'asset-360', th);
      await visit(page, '/reliability#finding=F-0308', th); await shot(page, 'finding-viewer', th);
      await visit(page, '/reliability', th);
      await openLinks(page);
      await t(page, 'queue-row').first().click();
      await shot(page, 'link-review', th);
    }
  });
});
